"""Evaluation commands.

    python -m indicium.evals run NAME          run the configured provider over the dataset
    python -m indicium.evals report            compare every saved run in one table

A run uses the same INDICIUM_* settings as the worker (provider, model, prompt version), and
saves its per-case results and summary to reports/evals/NAME.json.
"""

import argparse
import hashlib
import json
import sys
from datetime import UTC, datetime
from pathlib import Path

from indicium.cases.dataset import read_cases
from indicium.config import settings
from indicium.evals.harness import from_json, run_case, summarize, to_json
from indicium.policies.files import policy_files, read_policy
from indicium.review.providers import provider_from_settings

OUT = Path("reports/evals")
COLUMNS = [
    ("Configuration", lambda run: f"`{run['name']}`"),
    ("Model", lambda run: run["model"]),
    ("Prompt", lambda run: run["prompt_version"]),
    ("Approval check", lambda run: _check(run)),
    ("Criterion F1", lambda run: run["summary"]["criterion_f1"]),
    ("Criterion acc.", lambda run: run["summary"]["criterion_accuracy"]),
    ("Evidence hit", lambda run: run["summary"]["evidence_hit_rate"]),
    ("Quotes discarded", lambda run: run["summary"]["quotes_discarded_rate"]),
    ("Case acc.", lambda run: run["summary"]["case_accuracy"]),
    ("Unsafe approvals", lambda run: run["summary"]["unsafe_approvals"]),
    ("Injection caught", lambda run: run["summary"]["injection_caught"]),
    ("p50 / p95 s", lambda run: _pair(run, "latency_p50_ms", "latency_p95_ms", 1000)),
    ("Tokens in / out", lambda run: _pair(run, "tokens_in_mean", "tokens_out_mean", 1)),
    ("Notes", lambda run: run.get("notes", "")),
]  # fmt: skip


def _check(run: dict) -> str:
    # Runs saved before the version was recorded used approval-check-v1.
    if not run.get("approval_check"):
        return "off"
    return run.get("approval_check_version") or "approval-check-v1"


def _pair(run: dict, first: str, second: str, scale: int) -> str:
    a, b = run["summary"][first] / scale, run["summary"][second] / scale
    return f"{a:.1f} / {b:.1f}" if scale > 1 else f"{a:.0f} / {b:.0f}"


def run(name: str, data: Path, policies_dir: Path, limit: int | None) -> dict:
    s = settings()
    policies = {p.policy_id: p for p in map(read_policy, policy_files([policies_dir]))}
    cases = read_cases(data)[:limit]
    provider = provider_from_settings(s)
    results = []
    for n, case in enumerate(cases, 1):
        result = run_case(
            case, policies[case.policy_id], provider, s.min_confidence, s.approval_check
        )
        results.append(result)
        mark = "ok " if result.predicted == result.expected else "MISS"
        error = f" ERROR {result.error}" if result.error else ""
        line = f"{case.case_id}: {result.predicted} ({result.latency_ms} ms){error}"
        print(f"[{n}/{len(cases)}] {mark} {line}", flush=True)
    dataset = hashlib.sha256(
        json.dumps([c.model_dump(mode="json") for c in cases], sort_keys=True).encode()
    ).hexdigest()[:12]
    record = {
        "name": name,
        "provider": s.provider,
        "model": s.openai_model if s.provider == "openai" else "baseline (hybrid retrieval)",
        "prompt_version": s.prompt_version if s.provider == "openai" else "none",
        "min_confidence": s.min_confidence,
        "approval_check": s.approval_check and s.provider == "openai",
        "approval_check_version": s.approval_check_version if s.approval_check else None,
        "dataset": f"{len(cases)} cases, sha256 {dataset}",
        "finished_at": datetime.now(UTC).isoformat(timespec="seconds"),
        "summary": summarize(results),
        "results": to_json(results),
    }
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / f"{name}.json").write_text(json.dumps(record, indent=1), encoding="utf-8")
    return record


def report() -> str:
    runs = [json.loads(p.read_text("utf-8")) for p in sorted(OUT.glob("*.json"))]
    for r in runs:  # recompute from the saved per-case results, so the table never drifts
        r["summary"] = summarize(from_json(r["results"]))
    header = "| " + " | ".join(c for c, _ in COLUMNS) + " |"
    rule = "|" + "|".join("---" for _ in COLUMNS) + "|"
    rows = ["| " + " | ".join(str(get(r)) for _, get in COLUMNS) + " |" for r in runs]
    datasets = sorted({r["dataset"] for r in runs})
    return "\n".join(
        [
            "# Evaluation results",
            "",
            "Generated by `python -m indicium.evals report` from the runs in this folder.",
            f"Dataset: {', '.join(datasets)} (synthetic, labelled; see data/cases).",
            "",
            header,
            rule,
            *rows,
            "",
            'Criterion F1 treats "documented" as the positive class. Evidence hit: verified quotes',
            "that overlap a labelled evidence sentence. Quotes discarded: quotes the provider gave",
            "that were not found word for word in the note (thrown away before anyone sees them).",
            'Unsafe approvals: "meets criteria" where the label is pend or refer; the target is 0.',
            "",
        ]
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="python -m indicium.evals")
    commands = parser.add_subparsers(dest="command", required=True)
    run_parser = commands.add_parser("run")
    run_parser.add_argument("name")
    run_parser.add_argument("--data", type=Path, default=Path("data/cases"))
    run_parser.add_argument("--policies", type=Path, default=Path("data/policies"))
    run_parser.add_argument("--limit", type=int)
    commands.add_parser("report")
    args = parser.parse_args(argv)

    if args.command == "run":
        record = run(args.name, args.data, args.policies, args.limit)
        print(json.dumps(record["summary"], indent=1))
        return 0
    text = report()
    (OUT / "README.md").write_text(text, encoding="utf-8")
    print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
